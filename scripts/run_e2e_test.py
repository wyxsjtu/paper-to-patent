def assert_outputs(outdir: Path, md_path: Path, docx_path: Path) -> None:
    if not md_path.is_file():
        raise AssertionError(f"missing markdown: {md_path}")
    if not docx_path.is_file() or docx_path.stat().st_size < 1000:
        raise AssertionError(f"missing or tiny docx: {docx_path}")
    pngs = sorted(outdir.glob("fig_*.png"))
    if len(pngs) < 2:
        raise AssertionError("expected at least two generated PNG figures")
    text = md_path.read_text(encoding="utf-8")
    forbidden = ["本文", "我们", "作者", "新颖的", "先进的"]
    bad = [w for w in forbidden if w in text]
    if bad:
        raise AssertionError(f"forbidden words found: {bad}")
    for heading in ["技术领域", "背景技术", "发明内容", "技术效果", "附图说明", "具体实施方式"]:
        if heading not in text:
            raise AssertionError(f"missing heading: {heading}")


def main() -> int:
    ap = argparse.ArgumentParser(description="Run patent-disclosure end-to-end test")
    ap.add_argument("--workdir", default=str(DEFAULT_WORKDIR), help="test working directory")
    ap.add_argument("--keep", action="store_true", help="keep existing workdir contents")
    ap.add_argument("--skip-network", action="store_true", help="skip CNIPA and mermaid.ink network calls")
    args = ap.parse_args()

    workdir = Path(args.workdir).resolve()
    if workdir.exists() and not args.keep:
        shutil.rmtree(workdir)
    workdir.mkdir(parents=True, exist_ok=True)

    paper_dir = write_synthetic_latex(workdir)
    outdir = paper_dir / "patent_disclosure"
    parsed_json = workdir / "paper_parsed.json"
    patents_json = workdir / "patent_results.json"

    run([sys.executable, str(SCRIPT_DIR / "check_env.py"), "--json"], stdout=workdir / "env.json")
    run([sys.executable, str(SCRIPT_DIR / "parse_paper.py"), str(paper_dir), "-o", str(parsed_json)])
    parsed = json.loads(parsed_json.read_text(encoding="utf-8"))

    if args.skip_network:
        patents = []
        patents_json.write_text("[]", encoding="utf-8")
    else:
        run([
            sys.executable,
            str(SCRIPT_DIR / "patent_search.py"),
            "--query",
            "深度学习 图像分割",
            "--max",
            "3",
            "--source",
            "gov",
            "-o",
            str(patents_json),
        ])
        patents = json.loads(patents_json.read_text(encoding="utf-8"))
        real_patents = [p for p in patents if p.get("source") != "no_results"]
        if not real_patents:
            raise AssertionError("CNIPA patent search returned no real patent results")

    md_path = build_disclosure(parsed, patents, outdir)

    if args.skip_network and not shutil.which("mmdc"):
        # Create deterministic placeholder PNGs so offline CI can still test DOCX/image embedding.
        from PIL import Image, ImageDraw
        for i, label in enumerate(["系统架构", "方法流程"], start=1):
            img = Image.new("RGB", (1200, 700), "white")
            d = ImageDraw.Draw(img)
            d.rectangle((40, 40, 1160, 660), outline="black", width=4)
            d.text((80, 80), f"图{i} {label}", fill="black")
            img.save(outdir / f"fig_{i:02d}_{label}.png")
        text = md_path.read_text(encoding="utf-8")
        text = text.replace(text[text.find("```mermaid"):text.find("```", text.find("```mermaid") + 3) + 3], "![图1 系统整体架构](fig_01_系统架构.png)", 1)
        text = text.replace(text[text.find("```mermaid"):text.find("```", text.find("```mermaid") + 3) + 3], "![图2 方法流程](fig_02_方法流程.png)", 1)
        md_path.write_text(text, encoding="utf-8")
    else:
        r = run(["bash", str(SCRIPT_DIR / "mermaid_to_png.sh"), str(md_path), str(outdir)])
        updated = outdir / "_updated.md"
        if updated.is_file():
            md_path.write_text(updated.read_text(encoding="utf-8"), encoding="utf-8")

    docx_path = outdir / "20260602_自适应融合_patent_disclosure.docx"
    run([sys.executable, str(SCRIPT_DIR / "md_to_docx.py"), str(md_path), str(docx_path)])

    assert_outputs(outdir, md_path, docx_path)
    print(json.dumps({
        "status": "ok",
        "workdir": str(workdir),
        "paper_dir": str(paper_dir),
        "output_dir": str(outdir),
        "markdown": str(md_path),
        "docx": str(docx_path),
        "figures": [str(p) for p in sorted(outdir.glob("fig_*.png"))],
    }, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
