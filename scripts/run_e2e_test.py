def run(cmd: list[str], *, cwd: Path | None = None, stdout: Path | None = None) -> subprocess.CompletedProcess:
    print("[run]", " ".join(cmd), file=sys.stderr)
    kwargs = {
        "cwd": str(cwd) if cwd else None,
        "text": True,
        "capture_output": stdout is None,
        "timeout": 180,
    }
    if stdout is not None:
        with stdout.open("w", encoding="utf-8") as f:
            r = subprocess.run(cmd, stdout=f, stderr=subprocess.PIPE, text=True, cwd=str(cwd) if cwd else None, timeout=180)
    else:
        r = subprocess.run(cmd, **kwargs)
    if r.returncode != 0:
        if stdout is None:
            print(r.stdout, file=sys.stderr)
            print(r.stderr, file=sys.stderr)
        else:
            print(r.stderr, file=sys.stderr)
        raise RuntimeError(f"command failed: {' '.join(cmd)}")
    return r


